'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { createHash } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
function files(directory, relative = '') {
  return fs.readdirSync(path.join(directory, relative), { withFileTypes: true }).flatMap(entry => {
    const file = path.join(relative, entry.name);
    return entry.isDirectory() ? files(directory, file) : [{ path: file.split(path.sep).join('/'),
      sha256: hash(fs.readFileSync(path.join(directory, file))), mode: fs.statSync(path.join(directory, file)).mode & 0o777 }];
  }).sort((a, b) => a.path.localeCompare(b.path));
}
test('BUILD public dist and packed bytes remain reproducible under a private process umask', t => {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'wga-build-modes-'));
  t.after(() => fs.rmSync(temporary, { recursive: true, force: true }));
  const project = path.join(temporary, 'project');
  fs.mkdirSync(project);
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json')));
  const inputs = new Set(['package.json', 'tsconfig.json', 'src', 'scripts/build.cjs', 'scripts/toolchain.cjs',
    ...pkg.files.filter(file => file !== 'dist')]);
  for (const file of inputs) {
    const target = path.join(project, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.cpSync(path.join(root, file), target, { recursive: true });
  }
  // Use the existing compiler/types only; no SDK installation or shared dist.
  fs.symlinkSync(path.join(root, 'node_modules'), path.join(project, 'node_modules'), 'dir');
  pkg.bin = { 'wga-mode-fixture': './dist/build/mode-fixture.cjs' };
  fs.writeFileSync(path.join(project, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');
  fs.writeFileSync(path.join(project, 'src/build/mode-fixture.cjs'), '#!/usr/bin/env node\nprocess.stdout.write("mode fixture\\n");\n', { mode: 0o600 });
  fs.mkdirSync(path.join(project, 'verification'));
  const privateLog = path.join(project, 'verification/private.log');
  fs.writeFileSync(privateLog, 'private log', { mode: 0o600 });
  function build(mask) {
    const marker = path.join(project, `caller-mask-${mask}`);
    const child = 'process.umask(Number(process.argv[1]));require(process.argv[2]);require("node:fs").writeFileSync(process.argv[3], "caller permissions");';
    execFileSync(process.execPath, ['-e', child, String(mask), path.join(project, 'scripts/build.cjs'), marker],
      { cwd: project, encoding: 'utf8', timeout: 120000, maxBuffer: 2 * 1024 * 1024 });
    const snapshot = files(path.join(project, 'dist'));
    const destination = path.join(temporary, `archive-${mask}`);
    fs.mkdirSync(destination);
    const packed = JSON.parse(execFileSync('npm', ['pack', '--ignore-scripts', '--offline', '--json', '--pack-destination', destination],
      { cwd: project, encoding: 'utf8', timeout: 60000, maxBuffer: 2 * 1024 * 1024 }))[0];
    return { snapshot, integrity: packed.integrity, tarballSha256: hash(fs.readFileSync(path.join(destination, packed.filename))),
      callerMode: fs.statSync(marker).mode & 0o777, distMode: fs.statSync(path.join(project, 'dist')).mode & 0o777,
      nestedMode: fs.statSync(path.join(project, 'dist/build/profiles')).mode & 0o777 };
  }
  const shared = build(0o022), privateBuild = build(0o077);
  assert.deepEqual(privateBuild.snapshot.map(({ path: file, sha256 }) => [file, sha256]),
    shared.snapshot.map(({ path: file, sha256 }) => [file, sha256]), 'both builds use identical source and generated bytes');
  assert.equal(privateBuild.tarballSha256, shared.tarballSha256, 'a private caller umask must not change the actual packed artifact');
  assert.equal(privateBuild.integrity, shared.integrity, 'installed-fixture SRI remains valid after rebuilding');
  for (const output of [shared, privateBuild]) {
    assert.equal(output.distMode, 0o755);
    assert.equal(output.nestedMode, 0o755);
    for (const file of output.snapshot) assert.equal(file.mode, file.path === 'build/mode-fixture.cjs' ? 0o755 : 0o644, file.path);
  }
  assert.equal(shared.callerMode, 0o644);
  assert.equal(privateBuild.callerMode, 0o600, 'the build must preserve the caller umask');
  assert.equal(fs.statSync(privateLog).mode & 0o777, 0o600, 'normalization must not change private verification logs');
});
